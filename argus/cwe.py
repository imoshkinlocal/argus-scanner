"""Built-in offline reference for the CWEs reported by argus.

The catalog is deliberately small: it covers every CWE emitted by the bundled
Semgrep/Java rules plus the weaknesses that OSV advisories report most often.
Unknown identifiers still resolve to a stub entry with the official MITRE
link, so the GUI and the CLI never hide a CWE they do not know.

Descriptions are short on purpose: they explain the weakness to a developer,
not to a taxonomy expert.  The authoritative text always lives at MITRE.
"""

from __future__ import annotations

import dataclasses
import re
from typing import Dict, Iterable, List, Optional, Sequence

MITRE_URL = "https://cwe.mitre.org/data/definitions/{id}.html"

_CWE_RE = re.compile(r"(?i)^(?:cwe[-/:\s]*)?0*(\d+)\b")


@dataclasses.dataclass(frozen=True)
class CWEEntry:
    """One weakness from the local catalog."""

    id: int
    name: str
    name_ru: str
    category: str
    description: str
    consequences: str
    mitigations: Sequence[str]

    @property
    def cwe_id(self) -> str:
        return f"CWE-{self.id}"

    @property
    def url(self) -> str:
        return MITRE_URL.format(id=self.id)

    @property
    def known(self) -> bool:
        """True when the identifier exists in the shipped catalog."""
        return self.id in _CATALOG

    def to_dict(self) -> Dict[str, object]:
        return {
            "id": self.id,
            "cwe": self.cwe_id,
            "name": self.name,
            "name_ru": self.name_ru,
            "category": self.category,
            "description": self.description,
            "consequences": self.consequences,
            "mitigations": list(self.mitigations),
            "url": self.url,
            "known": self.known,
        }


def normalize_cwe(value: object) -> Optional[int]:
    """Parse ``CWE-79``, ``cwe/79``, ``79`` or ``CWE-079: ...`` into ``79``."""
    if value is None or isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value if value > 0 else None
    match = _CWE_RE.match(str(value).strip())
    if not match:
        return None
    number = int(match.group(1))
    return number if number > 0 else None


def format_cwe(value: object) -> str:
    """Return a canonical ``CWE-N`` label, or an empty string."""
    number = normalize_cwe(value)
    return f"CWE-{number}" if number is not None else ""


