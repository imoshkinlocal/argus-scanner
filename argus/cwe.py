_CATALOG: Dict[int, CWEEntry] = {entry.id: entry for entry in
                                 (CWEEntry(*row) for row in _RAW)}


def all_entries() -> List[CWEEntry]:
    """Return the whole catalog ordered by CWE number."""
    return [_CATALOG[key] for key in sorted(_CATALOG)]


def lookup(value: object) -> Optional[CWEEntry]:
    """Look up a CWE, falling back to a stub entry for unknown numbers."""
    number = normalize_cwe(value)
    if number is None:
        return None
    entry = _CATALOG.get(number)
    if entry is not None:
        return entry
    return CWEEntry(
        id=number,
        name=f"CWE-{number}",
        name_ru="Описание отсутствует в локальном справочнике",
        category="Другое",
        description=("Этот идентификатор не входит во встроенный каталог argus. "
                     "Откройте страницу MITRE, чтобы прочитать официальное описание."),
        consequences="Зависит от конкретной слабости.",
        mitigations=("Изучите официальное описание и рекомендации MITRE.",),
    )


def search(query: object) -> List[CWEEntry]:
    """Case-insensitive search by number, names, category or description."""
    text = str(query or "").strip().lower()
    if not text:
        return all_entries()
    number = normalize_cwe(text)
    if number is not None and (text.isdigit() or text.startswith("cwe")):
        entry = lookup(number)
        return [entry] if entry is not None else []
    words = [word for word in re.split(r"\s+", text) if word]
    matches: List[CWEEntry] = []
    for entry in all_entries():
        haystack = " ".join((
            entry.cwe_id, entry.name, entry.name_ru, entry.category,
            entry.description, entry.consequences, " ".join(entry.mitigations),
        )).lower()
        if all(word in haystack for word in words):
            matches.append(entry)
    return matches


def entries_for(values: Iterable[object]) -> List[CWEEntry]:
    """Resolve several CWE values, skipping anything unparsable."""
    seen: Dict[int, CWEEntry] = {}
    for value in values:
        entry = lookup(value)
        if entry is not None and entry.id not in seen:
            seen[entry.id] = entry
    return [seen[key] for key in sorted(seen)]


def categories() -> List[str]:
    """Sorted list of catalog categories, useful for filters."""
    return sorted({entry.category for entry in _CATALOG.values()})
